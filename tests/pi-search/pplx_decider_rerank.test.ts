import assert from "node:assert/strict";
import test from "node:test";
import { buildMockExtensionConfig } from "../../src/pi-search/config";
import { PiSearchBackendRuntime } from "../../src/pi-search/searcher/runtime";
import { SearchSessionStore } from "../../src/pi-search/search_cache";
import { ManagedTempSpillDir } from "../../src/pi-search/spill";
import { executeDirectSearchTool } from "../../src/pi-search/tool_handlers";
import { filterPredictor } from "../../src/pi-search/filter_config";
import { resolveFilterBackend, PPLX_AFFIRMATIVE_INSTRUCTION, PPLX_GENERAL_INSTRUCTION, QWEN3_AFFIRMATIVE_INSTRUCTION } from "../../src/pi-search/filter_backends";
import { createYesNoFilter, isSearchFilterEnabled, searchFilterGuidance } from "../../src/pi-search/yes_no_filter";

const env = {
  PI_SEARCH_FILTER_ENABLED: "1",
  PI_SEARCH_FILTER_ACTION: "rerank",
  PI_SEARCH_FILTER_PREDICTOR: "pplx_decider",
  PI_SEARCH_FILTER_QUESTION_SOURCE: "general",
  PI_SEARCH_FILTER_PREDICTOR_BASE_URL: "http://localhost:18286/v1",
  PI_SEARCH_FILTER_PREDICTOR_MODEL: "pplx-decider-flash-v1.2",
};
const model = env.PI_SEARCH_FILTER_PREDICTOR_MODEL;

function mockDecider(options: { reply?: unknown; status?: number } = {}) {
  const calls: Array<{ url: string; body: Record<string, unknown> }> = [];
  const request = (async (url, init) => {
    const body = JSON.parse(init!.body as string) as Record<string, unknown>;
    calls.push({ url: String(url), body });
    return options.status
      ? new Response("unavailable", { status: options.status })
      : Response.json(options.reply ?? { model, data: [{ index: 0, score: 0.85, margin: 2.8 }] });
  }) as typeof fetch;
  return { calls, request };
}

test("pplx_decider backend is explicitly selected and limited to direct two-tool filtering/rerank", () => {
  assert.equal(filterPredictor(env), "pplx_decider");
  const profile = resolveFilterBackend(env);
  assert.equal(profile.backend, "pplx-decider");
  assert.equal(profile.scoringApi, "decider_score");
  assert.equal(profile.instruction, PPLX_GENERAL_INSTRUCTION);
  assert.equal(profile.promptVersion, "pplx-decider-query-relevance-v1");
  assert.equal(isSearchFilterEnabled("pyserini-rest-2tool", env), true);
  assert.equal(isSearchFilterEnabled("pi-serini-3tool", env), false);
  assert.match(searchFilterGuidance(env), /No candidate is rejected/);
  assert.throws(() => resolveFilterBackend({ ...env, PI_SEARCH_FILTER_PREDICTOR_API: "score" }), /requires.*decider_score/);
  assert.throws(() => resolveFilterBackend({ ...env, PI_SEARCH_FILTER_PREDICTOR_BASE_URL: "", PI_SEARCH_FILTER_BASE_URL: "" }), /requires.*BASE_URL/);
});

test("general uses the current search query with fixed instruction; logs calibrated P(true) and raw margin", async () => {
  const mock = mockDecider();
  const result = await createYesNoFilter(env, mock.request)("solar halo ice crystals", "x".repeat(4100));
  assert.equal(mock.calls.length, 1);
  assert.equal(mock.calls[0]!.url, "http://localhost:18286/score");
  assert.deepEqual(mock.calls[0]!.body, {
    model, queries: "solar halo ice crystals", documents: ["x".repeat(4000)],
    instruction: PPLX_GENERAL_INSTRUCTION,
  });
  assert.equal(result.backend, "pplx-decider");
  assert.equal(result.scoringApi, "decider_score");
  assert.equal(result.probabilitySemantics, "calibrated_decision_noul");
  assert.equal(result.yesProbability, 0.85);
  assert.equal(result.rerankScore, 2.8);
  assert.equal(result.documentTruncated, true);
  assert.equal(result.documentTokens, undefined); // character cap, not a token cap
  assert.equal(result.scoringRequests, 1);
});

test("Qorrect question is generated by the existing generator, then scored with the affirmative instruction", async () => {
  const qenv = { ...env, PI_SEARCH_FILTER_QUESTION_SOURCE: "qorrect" };
  const mock = mockDecider({ reply: { model, data: [{ index: 0, score: 0.1, margin: -4 }] } });
  const qorrectProfile = resolveFilterBackend(qenv);
  assert.equal(qorrectProfile.instruction, PPLX_AFFIRMATIVE_INSTRUCTION);
  assert.equal(qorrectProfile.promptVersion, "pplx-decider-affirmative-evidence-v2");
  assert.equal(PPLX_AFFIRMATIVE_INSTRUCTION, QWEN3_AFFIRMATIVE_INSTRUCTION);
  assert.equal(PPLX_AFFIRMATIVE_INSTRUCTION,
    "Given a yes/no filter question, judge whether the document provides sufficient evidence to answer Yes to that question. A document that supports No, merely mentions the topic, or provides insufficient evidence does not meet the requirement. Use only the document.");
  const backendRuntime = new PiSearchBackendRuntime(buildMockExtensionConfig({ documents: [
    { docid: "one", text: "first" }, { docid: "two", text: "second" }, { docid: "three", text: "third" },
  ] }));
  const spillDir = new ManagedTempSpillDir("pplx-rerank-test-");
  let generated = 0;
  const deps = {
    backendRuntime, searchStore: new SearchSessionStore(), spillDir,
    nextSpillSequence: () => 1, rerankDepth: 3, filterAction: "rerank" as const,
    predictor: "pplx_decider" as const, questionSource: "qorrect" as const,
    generateFilterQuestion: async (query: string, reason: string) => {
      assert.equal(query, "first second third");
      assert.equal(reason, "why");
      generated++;
      return "Does this document describe the second item?";
    },
    documentFilter: createYesNoFilter(qenv, mock.request),
  };
  try {
    const result = await executeDirectSearchTool({ query: "first second third", hits: 2, reason: "why" }, undefined, { cwd: "." }, deps);
    assert.equal(generated, 1);
    assert.equal(mock.calls.length, 3);
    assert.ok(mock.calls.every(c => c.body.queries === "Does this document describe the second item?" && c.body.instruction === PPLX_AFFIRMATIVE_INSTRUCTION));
    assert.equal(result.details.rerank?.question, "Does this document describe the second item?");
    assert.equal(result.details.rerank?.candidateCount, 3);
    assert.equal(result.details.rerank?.yesNoScores?.length, 3);
    assert.ok(result.details.rerank?.yesNoScores?.every(s => !s.keep)); // No threshold-based removal
    assert.equal(result.details.retrievedDocids.length, 2);
    assert.equal(result.details.filter, undefined);
    assert.match(result.content[0].text, /pplx-decider reranked/);
  } finally {
    backendRuntime.dispose();
    spillDir.cleanup();
  }
});

test("reranking uses logit margin, not saturated probabilities, and fails closed", async () => {
  const backendRuntime = new PiSearchBackendRuntime(buildMockExtensionConfig({ documents: [
    { docid: "one", text: "first" }, { docid: "two", text: "second" }, { docid: "three", text: "third" },
  ] }));
  const spillDir = new ManagedTempSpillDir("pplx-margin-test-");
  const request = (async (_url: string | URL | Request, init?: RequestInit) => {
    const body = JSON.parse(init!.body as string) as { queries: string; instruction: string; documents: string[] };
    assert.equal(body.queries, "first second third");
    assert.equal(body.instruction, PPLX_GENERAL_INSTRUCTION);
    const passage = body.documents[0]!;
    const margin = passage.includes("second") ? 10 : passage.includes("third") ? 5 : 1;
    return Response.json({ model, data: [{ index: 0, score: 1, margin }] });
  }) as typeof fetch;
  const deps = {
    backendRuntime, searchStore: new SearchSessionStore(), spillDir,
    nextSpillSequence: () => 1, rerankDepth: 3, filterAction: "rerank" as const,
    predictor: "pplx_decider" as const, questionSource: "general" as const,
    documentFilter: createYesNoFilter(env, request),
  };
  try {
    const result = await executeDirectSearchTool({ query: "first second third", hits: 3, reason: "why" }, undefined, { cwd: "." }, deps);
    assert.deepEqual(result.details.retrievedDocids, ["two", "three", "one"]);
    assert.deepEqual(result.details.rerank?.scores.map(s => s.score), [1, 5, 10]);
    deps.documentFilter = createYesNoFilter(env, mockDecider({ status: 503 }).request);
    await assert.rejects(executeDirectSearchTool({ query: "first second third", hits: 3, reason: "why" }, undefined, { cwd: "." }, deps), /HTTP 503/);
  } finally {
    backendRuntime.dispose();
    spillDir.cleanup();
  }
  for (const reply of [
    {}, { model, data: [{ index: 0, score: 0.9 }] }, { model, data: [{ index: 0, score: 0.9, margin: "2" }] },
    { model, data: [{ index: 1, score: 0.9, margin: 2 }] },
    { model, data: [{ index: 0, score: -1, margin: 2 }] },
    { model: "wrong-model", data: [{ index: 0, score: 0.9, margin: 2 }] },
  ]) {
    await assert.rejects(createYesNoFilter(env, mockDecider({ reply }).request)("q", "doc"), /invalid or incomplete/);
  }
  await assert.rejects(createYesNoFilter({ ...env, PI_SEARCH_DECIDER_MAX_DOCUMENT_CHARS: "0" }, request)("q", "doc"), /must be an integer/);
});
